// Generates admin/js/fa-icons.js (the built-in icon picker list) from the Font Awesome Free 6.7.2 metadata.
// Run once by hand: node scripts/build-fa-icons.mjs   (needs internet; the admin itself never calls out).
// Output: window.RH_FA_ICONS = [[name, styles, searchTerms], ...]
//   name    icon name without the "fa-" prefix
//   styles  letters: s = solid (fas), r = regular (far), b = brands (fab)
//   terms   extra search words (label + Font Awesome search terms) not already in the name
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const VERSION = '6.7.2';
const URL_META = `https://cdn.jsdelivr.net/npm/@fortawesome/fontawesome-free@${VERSION}/metadata/icons.json`;
const CODE = { solid: 's', regular: 'r', brands: 'b' };

// Optional first argument: a local copy of metadata/icon-families.json or icons.json (from the npm package
// fontawesome-free@VERSION), for machines where the CDN is blocked.
let meta;
if (process.argv[2]) {
    meta = JSON.parse(readFileSync(process.argv[2], 'utf8'));
} else {
    const res = await fetch(URL_META);
    if (!res.ok) throw new Error('Download failed: HTTP ' + res.status);
    meta = await res.json();
}

const rows = [];
for (const [name, info] of Object.entries(meta)) {
    // icons.json lists free styles as strings; icon-families.json (npm package) as {family, style} objects.
    const freeList = info.free || (info.familyStylesByLicense && info.familyStylesByLicense.free) || [];
    const free = freeList
        .filter((s) => typeof s === 'string' || s.family === 'classic')
        .map((s) => (typeof s === 'string' ? s : s.style))
        .filter((s) => CODE[s]);
    if (!free.length) continue; // Pro-only icon
    if (!/^[a-z0-9-]+$/.test(name)) continue; // the admin only stores plain names; skip anything else
    const styles = ['solid', 'regular', 'brands'].filter((s) => free.includes(s)).map((s) => CODE[s]).join('');
    const nameWords = new Set(name.split('-'));
    const words = [];
    const add = (w) => {
        w = String(w).toLowerCase().trim();
        if (!w || w === name || nameWords.has(w) || words.includes(w)) return;
        words.push(w);
    };
    add(info.label);
    for (const t of (info.search && info.search.terms) || []) add(t);
    for (const t of (info.aliases && info.aliases.names) || []) add(t);
    rows.push([name, styles, words.slice(0, 12).join(' ')]);
}
rows.sort((a, b) => (a[0] < b[0] ? -1 : 1));

const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, '..', 'admin', 'js', 'fa-icons.js');
const body = rows.map((r) => JSON.stringify(r)).join(',\n');
writeFileSync(
    out,
    `/* Generated by scripts/build-fa-icons.mjs from Font Awesome Free ${VERSION} metadata. Do not edit by hand.\n` +
        `   Row: [name without "fa-", styles (s solid, r regular, b brands), extra search words]. */\n` +
        `window.RH_FA_ICONS = [\n${body}\n];\n`
);
console.log(`Wrote ${rows.length} icons to ${out}`);
